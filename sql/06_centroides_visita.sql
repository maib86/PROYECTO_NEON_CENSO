-- =====================================================================================
--  06 — CAPA DE VISITA: UN PUNTO POR FINCA
-- =====================================================================================
--  Crea la capa de puntos sobre la que vive el formulario de visita. Un punto por
--  polígono, generado dentro de la finca. El polígono queda como contexto de
--  referencia; lo que se edita en campo es el punto.
--
--  POR QUÉ UNA CAPA APARTE Y NO CAMPOS NUEVOS EN EL POLÍGONO
--    · Lo que un censista edita en campo es la visita, no la geometría de la finca.
--      Separar las dos cosas evita que un toque en el celular mueva un vértice.
--    · Un punto pesa cientos de veces menos que un polígono. En QField, con miles
--      de fincas, eso es la diferencia entre un proyecto que sincroniza en segundos
--      y uno que no termina.
--    · Permite varias visitas por finca más adelante (revisitas) sin tocar la capa
--      base.
--
--  CENTROIDE vs PUNTO INTERIOR
--  ST_Centroid calcula el centro de masa, y en fincas con forma de L, de C o con
--  islas ese punto puede caer FUERA del polígono. ST_PointOnSurface garantiza un
--  punto dentro. Para una visita de campo lo que importa es que el punto esté en
--  la finca, así que se usa ST_PointOnSurface. Para fincas convexas da lo mismo.
--
--  ORDEN: ejecutar como neondb_owner, después del 03 (los roles ya deben existir).
-- =====================================================================================


-- =====================================================================================
--  BLOQUE 1 — Tabla de visita
-- =====================================================================================

CREATE TABLE mgn.finca_visita (

    -- Identificación
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finca_id            bigint NOT NULL
                        REFERENCES mgn.deteccion_cambio(id) ON DELETE CASCADE,

    -- Reparto: se copia del polígono para que RLS funcione igual en esta capa
    lote                text    NOT NULL CHECK (lote IN ('A','B')),
    codigo_upm          text,

    -- ---- Formulario de visita ----
    -- Campos estructurales del operativo. Los campos temáticos del cuestionario
    -- real del censo se agregan aquí cuando se definan; no se inventan ahora.
    estado_visita       text    NOT NULL DEFAULT 'pendiente'
                                CHECK (estado_visita IN
                                    ('pendiente','visitada','no_localizada',
                                     'rechazo','revisita')),
    encuestador         text,          -- en QField: default @cloud_username
    fecha_visita        timestamptz,   -- en QField: default now()
    observaciones       text,

    -- ---- Posición real al registrar (se llena desde QField con GNSS) ----
    precision_gnss_m    double precision,
    posicion_registro   geometry(Point, 4326),

    -- ---- Auditoría (trigger) ----
    creado_por          text        NOT NULL DEFAULT current_user,
    fecha_creacion      timestamptz NOT NULL DEFAULT now(),
    editado_por         text        NOT NULL DEFAULT current_user,
    fecha_edicion       timestamptz NOT NULL DEFAULT now(),

    -- ---- Geometría: el punto de visita ----
    geom                geometry(Point, 5367) NOT NULL,

    UNIQUE (finca_id)   -- una visita por finca en el piloto; quitar para revisitas
);

COMMENT ON TABLE  mgn.finca_visita IS
    'Punto de visita por finca. Aquí vive el formulario que se edita en campo.';
COMMENT ON COLUMN mgn.finca_visita.estado_visita IS
    'pendiente | visitada | no_localizada | rechazo | revisita';
COMMENT ON COLUMN mgn.finca_visita.encuestador IS
    'Quien hizo la visita. Desde QField se llena con @cloud_username; desde escritorio lo deja vacío y manda editado_por.';


-- =====================================================================================
--  BLOQUE 2 — Índices y auditoría
-- =====================================================================================

CREATE INDEX idx_fv_geom     ON mgn.finca_visita USING GIST (geom);
CREATE INDEX idx_fv_lote     ON mgn.finca_visita (lote);
CREATE INDEX idx_fv_estado   ON mgn.finca_visita (estado_visita);
CREATE INDEX idx_fv_finca    ON mgn.finca_visita (finca_id);

-- Mismo trigger de auditoría que la capa de polígonos.
CREATE TRIGGER trg_sello_auditoria
    BEFORE INSERT OR UPDATE ON mgn.finca_visita
    FOR EACH ROW EXECUTE FUNCTION mgn.fn_sello_auditoria();

-- Si se marca visitada y no hay fecha, la pone. Evita visitas "sin cuándo".
CREATE OR REPLACE FUNCTION mgn.fn_fecha_visita_auto()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado_visita <> 'pendiente' AND NEW.fecha_visita IS NULL THEN
        NEW.fecha_visita := now();
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_fecha_visita_auto
    BEFORE INSERT OR UPDATE ON mgn.finca_visita
    FOR EACH ROW EXECUTE FUNCTION mgn.fn_fecha_visita_auto();


-- =====================================================================================
--  BLOQUE 3 — Generar un punto por finca
-- =====================================================================================

INSERT INTO mgn.finca_visita (finca_id, lote, codigo_upm, geom)
SELECT
    id,
    lote,
    codigo_upm,
    ST_PointOnSurface(geom)        -- alternativa: ST_Centroid(geom)
FROM mgn.deteccion_cambio;


-- =====================================================================================
--  BLOQUE 4 — Permisos y control de acceso (idénticos a la capa de polígonos)
-- =====================================================================================

GRANT SELECT, INSERT, UPDATE, DELETE ON mgn.finca_visita
    TO edit_lote_a, edit_lote_b;

GRANT USAGE, SELECT ON SEQUENCE mgn.finca_visita_id_seq
    TO edit_lote_a, edit_lote_b;

ALTER TABLE mgn.finca_visita ENABLE ROW LEVEL SECURITY;

CREATE POLICY pol_lectura_total ON mgn.finca_visita
    FOR SELECT TO edit_lote_a, edit_lote_b USING (true);

CREATE POLICY pol_escritura_lote_a ON mgn.finca_visita
    FOR ALL TO edit_lote_a
    USING (lote = 'A') WITH CHECK (lote = 'A');

CREATE POLICY pol_escritura_lote_b ON mgn.finca_visita
    FOR ALL TO edit_lote_b
    USING (lote = 'B') WITH CHECK (lote = 'B');


-- =====================================================================================
--  BLOQUE 5 — Vistas que alimentan el tablero
-- =====================================================================================
--  El tablero lee SOLO estas vistas, con un rol de solo lectura (Bloque 6).
--  Así el generador del tablero nunca toca las tablas ni puede escribir.
-- =====================================================================================

-- 5.1 Resumen por lote (equipo)
CREATE OR REPLACE VIEW mgn.v_tab_resumen AS
SELECT
    lote,
    count(*)                                                 AS fincas,
    count(*) FILTER (WHERE estado_visita = 'visitada')       AS visitadas,
    count(*) FILTER (WHERE estado_visita = 'no_localizada')  AS no_localizadas,
    count(*) FILTER (WHERE estado_visita = 'rechazo')        AS rechazos,
    count(*) FILTER (WHERE estado_visita = 'revisita')       AS revisitas,
    count(*) FILTER (WHERE estado_visita = 'pendiente')      AS pendientes,
    round(100.0 * count(*) FILTER (WHERE estado_visita <> 'pendiente')
          / NULLIF(count(*),0), 1)                           AS avance_pct,
    max(fecha_visita)                                        AS ultima_visita
FROM mgn.finca_visita
GROUP BY lote
ORDER BY lote;

-- 5.2 Por encuestador (quien visitó: QField llena encuestador, escritorio editado_por)
CREATE OR REPLACE VIEW mgn.v_tab_encuestador AS
SELECT
    coalesce(encuestador, editado_por)                       AS persona,
    lote,
    count(*)                                                 AS visitas,
    count(*) FILTER (WHERE estado_visita = 'visitada')       AS visitadas,
    count(*) FILTER (WHERE estado_visita IN ('no_localizada','rechazo','revisita'))
                                                             AS incidencias,
    min(fecha_visita)                                        AS primera,
    max(fecha_visita)                                        AS ultima
FROM mgn.finca_visita
WHERE estado_visita <> 'pendiente'
GROUP BY 1, 2
ORDER BY visitas DESC;

-- 5.3 Por día (hora de Costa Rica)
CREATE OR REPLACE VIEW mgn.v_tab_diario AS
SELECT
    (fecha_visita AT TIME ZONE 'America/Costa_Rica')::date   AS dia,
    lote,
    count(*)                                                 AS visitas
FROM mgn.finca_visita
WHERE estado_visita <> 'pendiente' AND fecha_visita IS NOT NULL
GROUP BY 1, 2
ORDER BY dia, lote;

-- 5.4 Puntos para el mapa, ya en WGS84 (lo que entiende el navegador)
CREATE OR REPLACE VIEW mgn.v_tab_puntos AS
SELECT
    v.id,
    v.finca_id,
    v.lote,
    v.codigo_upm,
    v.estado_visita,
    coalesce(v.encuestador, CASE WHEN v.estado_visita <> 'pendiente'
                                 THEN v.editado_por END)     AS persona,
    to_char(v.fecha_visita AT TIME ZONE 'America/Costa_Rica',
            'DD/MM HH24:MI')                                 AS cuando,
    ST_Y(ST_Transform(v.geom, 4326))                         AS lat,
    ST_X(ST_Transform(v.geom, 4326))                         AS lon
FROM mgn.finca_visita v;

-- 5.5 Últimos movimientos
CREATE OR REPLACE VIEW mgn.v_tab_movimientos AS
SELECT
    v.finca_id,
    v.lote,
    v.codigo_upm,
    v.estado_visita,
    coalesce(v.encuestador, v.editado_por)                   AS persona,
    to_char(v.fecha_edicion AT TIME ZONE 'America/Costa_Rica',
            'DD/MM HH24:MI')                                 AS cuando,
    v.observaciones
FROM mgn.finca_visita v
WHERE v.estado_visita <> 'pendiente'
ORDER BY v.fecha_edicion DESC
LIMIT 25;


-- =====================================================================================
--  BLOQUE 6 — Rol de SOLO LECTURA para el tablero
-- =====================================================================================
--  El generador del tablero se conecta con este rol. No puede escribir nada ni
--  leer las tablas: solo las vistas. Si la credencial se filtrara, lo peor que
--  pasa es que alguien vea el avance.
--
--  La contraseña NO se escribe en este archivo. Se pasa como variable de psql al
--  ejecutar, tomada de .env (la misma que trae DATABASE_URL_TABLERO):
--      psql "$DATABASE_URL" -1 -v ON_ERROR_STOP=1 -v clave_tablero="$CLAVE" -f ...
--  Sin -v clave_tablero, psql no interpola y la sentencia falla (no crea el rol).
-- =====================================================================================

CREATE ROLE tablero_lectura LOGIN PASSWORD :'clave_tablero';

GRANT USAGE ON SCHEMA mgn TO tablero_lectura;

GRANT SELECT ON mgn.v_tab_resumen,
                mgn.v_tab_encuestador,
                mgn.v_tab_diario,
                mgn.v_tab_puntos,
                mgn.v_tab_movimientos
    TO tablero_lectura;

-- Las vistas corren con los permisos de su dueño (neondb_owner), por lo que el
-- rol tablero_lectura ve TODAS las filas sin necesitar políticas propias.


