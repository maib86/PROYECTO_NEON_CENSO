-- =====================================================================================
--  BLOQUE 7 — Vista de control de avance
-- =====================================================================================
--  Para revisar el estado del encargo sin abrir QGIS.
-- =====================================================================================

CREATE OR REPLACE VIEW mgn.v_avance AS
SELECT
    provincia,
    estado_revision,
    count(*)                                   AS poligonos,
    round(sum(ST_Area(geom)) / 10000.0, 2)     AS hectareas,
    max(fecha_edicion)                         AS ultima_edicion,
    string_agg(DISTINCT editado_por, ', ')     AS editoras
FROM mgn.asentamientos_informales
GROUP BY provincia, estado_revision
ORDER BY provincia, estado_revision;

GRANT SELECT ON mgn.v_avance TO edit_limon, edit_guanacaste;


