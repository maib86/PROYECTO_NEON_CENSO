-- =====================================================================================
--  ASENTAMIENTOS INFORMALES — Esquema de edición concurrente multiusuario
-- =====================================================================================
--  Motor      : PostgreSQL 16+ con PostGIS 3.x
--  Hospedaje  : Neon (plan gratuito) u otro PostgreSQL gestionado
--  SRC        : CRTM05 — EPSG:5367
--  Editoras   : 2 (asignación por provincia: Limón / Guanacaste)
--  Volumen    : ~10.000 polígonos
--
--  PRINCIPIO DE DISEÑO
--  El reparto del trabajo no se sostiene con disciplina de las personas: se impone
--  en la base mediante Row Level Security. Cada editora puede LEER la capa completa
--  pero solo puede ESCRIBIR sobre los registros de su provincia asignada. Esto hace
--  estructuralmente imposible pisar el trabajo de la otra.
--
--  ORDEN DE EJECUCIÓN
--  Bloques 1 a 7 en secuencia, conectada como el rol propietario/administrador.
--  Los bloques 5 y 6 requieren sustituir las contraseñas marcadas con <<< >>>.
-- =====================================================================================


-- =====================================================================================
--  BLOQUE 1 — Extensiones y esquema
-- =====================================================================================

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE SCHEMA IF NOT EXISTS mgn;

COMMENT ON SCHEMA mgn IS
    'Capas de trabajo del encargo INEC — actualización de asentamientos informales.';


-- =====================================================================================
--  BLOQUE 2 — Tabla principal
-- =====================================================================================
--  Notas de diseño:
--   - La llave primaria es un entero IDENTITY. QGIS REQUIERE una llave primaria entera
--     única para editar una capa PostGIS de forma confiable. Se usa GENERATED BY DEFAULT
--     (no ALWAYS) para que QGIS pueda insertar sin fricción.
--   - La geometría se declara MultiPolygon: QGIS y ogr2ogr promueven polígonos simples
--     a multiparte sin problema, y evita el error inverso al cargar geometrías con islas.
--   - provincia es NOT NULL y restringida por CHECK porque es la columna sobre la que
--     opera el control de acceso. Un NULL ahí dejaría una fila sin dueña.
-- =====================================================================================

CREATE TABLE mgn.asentamientos_informales (

    -- Identificación
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo              text,
    nombre              text,

    -- Ubicación administrativa (provincia gobierna el control de acceso)
    provincia           text        NOT NULL
                                    CHECK (provincia IN ('Limón', 'Guanacaste')),
    canton              text,
    distrito            text,

    -- Atributos temáticos — ajustar a la ficha técnica del encargo
    tipo_asentamiento   text,
    fuente_insumo       text,
    anio_referencia     integer     CHECK (anio_referencia BETWEEN 1990 AND 2100),

    -- Control de avance
    estado_revision     text        NOT NULL DEFAULT 'pendiente'
                                    CHECK (estado_revision IN
                                        ('pendiente','en_proceso','revisado','validado')),
    observaciones       text,

    -- Auditoría (poblada automáticamente por el trigger del Bloque 4)
    creado_por          text        NOT NULL DEFAULT current_user,
    fecha_creacion      timestamptz NOT NULL DEFAULT now(),
    editado_por         text        NOT NULL DEFAULT current_user,
    fecha_edicion       timestamptz NOT NULL DEFAULT now(),

    -- Geometría
    geom                geometry(MultiPolygon, 5367) NOT NULL
);

COMMENT ON TABLE  mgn.asentamientos_informales IS
    'Capa única de asentamientos informales. Edición concurrente, reparto por provincia.';
COMMENT ON COLUMN mgn.asentamientos_informales.provincia IS
    'Determina qué editora puede escribir la fila. No modificar sin coordinación.';
COMMENT ON COLUMN mgn.asentamientos_informales.estado_revision IS
    'pendiente -> en_proceso -> revisado -> validado';


-- =====================================================================================
--  BLOQUE 3 — Índices y validación geométrica
-- =====================================================================================

-- Índice espacial: obligatorio. Sin esto el renderizado por extensión es lento.
CREATE INDEX idx_asent_geom
    ON mgn.asentamientos_informales USING GIST (geom);

-- Índice sobre la columna de reparto: la usan tanto RLS como el filtro de QGIS.
CREATE INDEX idx_asent_provincia
    ON mgn.asentamientos_informales (provincia);

CREATE INDEX idx_asent_estado
    ON mgn.asentamientos_informales (estado_revision);

-- Validez geométrica.
-- Se declara NOT VALID para que no bloquee la carga inicial de datos heredados que
-- puedan traer geometrías inválidas. Tras limpiar con ST_MakeValid, ejecutar:
--     ALTER TABLE mgn.asentamientos_informales VALIDATE CONSTRAINT chk_geom_valida;
-- A partir de ese momento rechaza cualquier edición que produzca geometría inválida.
ALTER TABLE mgn.asentamientos_informales
    ADD CONSTRAINT chk_geom_valida CHECK (ST_IsValid(geom)) NOT VALID;


-- =====================================================================================
--  BLOQUE 4 — Trigger de auditoría
-- =====================================================================================
--  Registra automáticamente quién tocó cada polígono y cuándo. No depende de que la
--  editora llene el campo. En INSERT fija creación y edición; en UPDATE preserva la
--  creación original e ignora cualquier intento de sobrescribirla desde el cliente.
-- =====================================================================================

CREATE OR REPLACE FUNCTION mgn.fn_sello_auditoria()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.creado_por     := current_user;
        NEW.fecha_creacion := now();
    ELSE
        NEW.creado_por     := OLD.creado_por;
        NEW.fecha_creacion := OLD.fecha_creacion;
    END IF;

    NEW.editado_por   := current_user;
    NEW.fecha_edicion := now();

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sello_auditoria
    BEFORE INSERT OR UPDATE ON mgn.asentamientos_informales
    FOR EACH ROW EXECUTE FUNCTION mgn.fn_sello_auditoria();


-- =====================================================================================
--  BLOQUE 5 — Roles de edición
-- =====================================================================================
--  Un rol por persona. Nunca compartir credenciales: el valor del campo editado_por
--  depende enteramente de que cada quien entre con su propio usuario.
--
--  <<< SUSTITUIR LAS CONTRASEÑAS ANTES DE EJECUTAR >>>
-- =====================================================================================

CREATE ROLE edit_limon      LOGIN PASSWORD '<<<CAMBIAR_CONTRASENA_1>>>';
CREATE ROLE edit_guanacaste LOGIN PASSWORD '<<<CAMBIAR_CONTRASENA_2>>>';

GRANT USAGE ON SCHEMA mgn TO edit_limon, edit_guanacaste;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON mgn.asentamientos_informales
    TO edit_limon, edit_guanacaste;

-- Lectura del catálogo de PostGIS (necesaria para que QGIS liste la capa).
GRANT SELECT ON geometry_columns, spatial_ref_sys TO edit_limon, edit_guanacaste;


-- =====================================================================================
--  BLOQUE 6 — Row Level Security: el reparto del trabajo, impuesto por la base
-- =====================================================================================
--  Resultado:
--    · Ambas editoras VEN los 10.000 polígonos completos (contexto nacional).
--    · edit_limon solo puede INSERT/UPDATE/DELETE donde provincia = 'Limón'.
--    · edit_guanacaste solo donde provincia = 'Guanacaste'.
--    · El WITH CHECK impide además reetiquetar una fila hacia la otra provincia.
--
--  Las políticas permisivas se combinan con OR, por lo que pol_lectura_total garantiza
--  que el SELECT siga devolviendo todo pese a las políticas de escritura.
-- =====================================================================================

ALTER TABLE mgn.asentamientos_informales ENABLE ROW LEVEL SECURITY;

-- Lectura completa para todas las editoras
CREATE POLICY pol_lectura_total
    ON mgn.asentamientos_informales
    FOR SELECT
    TO edit_limon, edit_guanacaste
    USING (true);

-- Escritura acotada a Limón
CREATE POLICY pol_escritura_limon
    ON mgn.asentamientos_informales
    FOR ALL
    TO edit_limon
    USING      (provincia = 'Limón')
    WITH CHECK (provincia = 'Limón');

-- Escritura acotada a Guanacaste
CREATE POLICY pol_escritura_guanacaste
    ON mgn.asentamientos_informales
    FOR ALL
    TO edit_guanacaste
    USING      (provincia = 'Guanacaste')
    WITH CHECK (provincia = 'Guanacaste');

