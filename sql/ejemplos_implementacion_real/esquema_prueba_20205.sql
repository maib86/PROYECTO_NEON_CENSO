-- =====================================================================================
--  PRUEBA — Detección de cambio, distrito 20205 (San Ramón, Alajuela)
--  Esquema de edición concurrente multiusuario
-- =====================================================================================
--  Motor      : PostgreSQL 17 con PostGIS 3.x  (Neon, plan gratuito)
--  SRC destino: CRTM05 — EPSG:5367   (el GeoJSON de origen viene en WGS84 / EPSG:4326)
--  Editoras   : 2  (reparto por lote de UPM)
--  Volumen    : 1.432 polígonos
--
--  QUÉ ES ESTE ARCHIVO
--  Versión de PRUEBA del esquema, ajustada a la estructura real del archivo
--  20205.geojson (salida del pipeline de detección de cambio 2021–2026).
--  El mecanismo es idéntico al de la capa definitiva: cambia la columna que
--  gobierna el reparto (aquí `lote`, allá `provincia`) y nada más.
--
--  REPARTO
--  El distrito tiene 10 UPM. Se reparten en dos lotes balanceados por cantidad:
--    Lote A — UPM 001, 002, 003, 006, 010  →  709 polígonos
--    Lote B — UPM 004, 005, 007, 008, 009  →  723 polígonos
--
--  ORDEN DE EJECUCIÓN
--  Bloques 1 a 4 primero. Luego la carga (Anexo A). Después bloques 5 a 8.
--  El Bloque 6 requiere sustituir las contraseñas marcadas con <<< >>>.
-- =====================================================================================


-- =====================================================================================
--  BLOQUE 1 — Extensiones y esquema
-- =====================================================================================

CREATE EXTENSION IF NOT EXISTS postgis;

CREATE SCHEMA IF NOT EXISTS mgn;

COMMENT ON SCHEMA mgn IS
    'Capas de trabajo INEC — prueba de edición concurrente, distrito 20205.';


-- =====================================================================================
--  BLOQUE 2 — Tabla principal
-- =====================================================================================
--  Notas de diseño:
--   - `id` entero IDENTITY: QGIS REQUIERE una llave primaria entera única para editar
--     una capa PostGIS de forma confiable. El identificador original del pipeline
--     (del tipo '-940899+112531') se conserva aparte, en `id_origen`.
--   - Geometría MultiPolygon: el archivo trae 1.232 Polygon + 200 MultiPolygon.
--     Se unifican con ST_Multi al cargar.
--   - `lote` es NOT NULL y restringida por CHECK: es la columna sobre la que opera
--     el control de acceso. Un NULL ahí dejaría una fila sin dueña.
-- =====================================================================================

CREATE TABLE mgn.deteccion_cambio (

    -- Identificación
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origen           text        NOT NULL,

    -- Reparto del trabajo (gobierna el control de acceso del Bloque 7)
    lote                text        NOT NULL CHECK (lote IN ('A', 'B')),

    -- Ubicación administrativa
    codigo_dta          integer,
    codigo_upm          text,
    region              text,

    -- Resultados del pipeline de detección (2021 -> 2026)
    anio_t1             integer,
    anio_t2             integer,
    tipo_cambio         integer,
    priority_cat        text,
    spectral_risk       double precision,
    fp_risk             double precision,
    fp_marca_alto       integer,
    margin_t2_dir       double precision,
    coverage_s2         double precision,
    t1_gap              double precision,
    conteo              integer,

    -- Probabilidades por clase, antes (t1) y después (t2)
    p0_t1               double precision,
    p1_t1               double precision,
    p2_t1               double precision,
    p3_t1               double precision,
    p0_t2               double precision,
    p1_t2               double precision,
    p2_t2               double precision,
    p3_t2               double precision,

    -- Métricas de superficie del origen (referencia; el área real se calcula de geom)
    area_ha_origen      double precision,
    area_m2_origen      double precision,

    -- Control de avance
    estado_revision     text        NOT NULL DEFAULT 'pendiente'
                                    CHECK (estado_revision IN
                                        ('pendiente','en_proceso','revisado','validado','descartado')),
    observaciones       text,

    -- Auditoría (poblada automáticamente por el trigger del Bloque 4)
    creado_por          text        NOT NULL DEFAULT current_user,
    fecha_creacion      timestamptz NOT NULL DEFAULT now(),
    editado_por         text        NOT NULL DEFAULT current_user,
    fecha_edicion       timestamptz NOT NULL DEFAULT now(),

    -- Geometría
    geom                geometry(MultiPolygon, 5367) NOT NULL
);

COMMENT ON TABLE  mgn.deteccion_cambio IS
    'Capa única de detección de cambio, distrito 20205. Edición concurrente, reparto por lote.';
COMMENT ON COLUMN mgn.deteccion_cambio.lote IS
    'Determina qué editora puede escribir la fila. A = UPM 001,002,003,006,010 · B = UPM 004,005,007,008,009';
COMMENT ON COLUMN mgn.deteccion_cambio.estado_revision IS
    'pendiente -> en_proceso -> revisado -> validado | descartado (falso positivo)';
COMMENT ON COLUMN mgn.deteccion_cambio.id_origen IS
    'Identificador original del pipeline. No es la llave primaria: QGIS necesita un entero.';


-- =====================================================================================
--  BLOQUE 3 — Índices
-- =====================================================================================

-- Índice espacial: obligatorio. Sin esto el renderizado por extensión es lento.
CREATE INDEX idx_dc_geom      ON mgn.deteccion_cambio USING GIST (geom);

-- Índice sobre la columna de reparto: la usan tanto RLS como el filtro de QGIS.
CREATE INDEX idx_dc_lote      ON mgn.deteccion_cambio (lote);

CREATE INDEX idx_dc_upm       ON mgn.deteccion_cambio (codigo_upm);
CREATE INDEX idx_dc_estado    ON mgn.deteccion_cambio (estado_revision);
CREATE INDEX idx_dc_prioridad ON mgn.deteccion_cambio (priority_cat);


-- =====================================================================================
--  BLOQUE 4 — Trigger de auditoría
-- =====================================================================================
--  Registra automáticamente quién tocó cada polígono y cuándo. No depende de que la
--  editora llene el campo. En INSERT fija creación y edición; en UPDATE preserva la
--  creación original e ignora cualquier intento de sobrescribirla desde el cliente.
-- =====================================================================================

CREATE OR REPLACE FUNCTION mgn.fn_sello_auditoria()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.creado_por     := current_user;
        NEW.fecha_creacion := now();
    ELSE
        NEW.creado_por     := OLD.creado_por;
        NEW.fecha_creacion := OLD.fecha_creacion;
    END IF;

    NEW.editado_por   := current_user;
    NEW.fecha_edicion := now();

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sello_auditoria
    BEFORE INSERT OR UPDATE ON mgn.deteccion_cambio
    FOR EACH ROW EXECUTE FUNCTION mgn.fn_sello_auditoria();


