-- =====================================================================================
--  BLOQUE 6 — Roles de edición
-- =====================================================================================
--  Un rol por persona. Nunca compartir credenciales: el valor del campo editado_por
--  depende enteramente de que cada quien entre con su propio usuario.
--
--  <<< SUSTITUIR LAS CONTRASEÑAS ANTES DE EJECUTAR >>>
--  16 caracteres o más, sin tildes ni eñes, distintas entre sí.
-- =====================================================================================

CREATE ROLE edit_lote_a LOGIN PASSWORD '<<<CAMBIAR_CONTRASENA_A>>>';
CREATE ROLE edit_lote_b LOGIN PASSWORD '<<<CAMBIAR_CONTRASENA_B>>>';

GRANT USAGE ON SCHEMA mgn TO edit_lote_a, edit_lote_b;

GRANT SELECT, INSERT, UPDATE, DELETE
    ON mgn.deteccion_cambio
    TO edit_lote_a, edit_lote_b;

-- La secuencia de la llave primaria: necesaria para que puedan crear polígonos nuevos.
GRANT USAGE, SELECT
    ON SEQUENCE mgn.deteccion_cambio_id_seq
    TO edit_lote_a, edit_lote_b;

-- Lectura del catálogo de PostGIS (necesaria para que QGIS liste la capa).
GRANT SELECT ON geometry_columns, geography_columns, spatial_ref_sys
    TO edit_lote_a, edit_lote_b;


-- =====================================================================================
--  BLOQUE 7 — Row Level Security: el reparto del trabajo, impuesto por la base
-- =====================================================================================
--  Resultado:
--    · Ambas editoras VEN los 1.432 polígonos completos (contexto del distrito).
--    · edit_lote_a solo puede INSERT/UPDATE/DELETE donde lote = 'A'.
--    · edit_lote_b solo donde lote = 'B'.
--    · El WITH CHECK impide además reetiquetar una fila hacia el otro lote.
--
--  Las políticas permisivas se combinan con OR, por lo que pol_lectura_total garantiza
--  que el SELECT siga devolviendo todo pese a las políticas de escritura.
-- =====================================================================================

ALTER TABLE mgn.deteccion_cambio ENABLE ROW LEVEL SECURITY;

CREATE POLICY pol_lectura_total
    ON mgn.deteccion_cambio
    FOR SELECT
    TO edit_lote_a, edit_lote_b
    USING (true);

CREATE POLICY pol_escritura_lote_a
    ON mgn.deteccion_cambio
    FOR ALL
    TO edit_lote_a
    USING      (lote = 'A')
    WITH CHECK (lote = 'A');

CREATE POLICY pol_escritura_lote_b
    ON mgn.deteccion_cambio
    FOR ALL
    TO edit_lote_b
    USING      (lote = 'B')
    WITH CHECK (lote = 'B');

-- NOTA: el rol propietario (neondb_owner) omite RLS por defecto. Eso es intencional:
