-- =====================================================================================
--  BLOQUE 8 — Vista de control de avance
-- =====================================================================================

CREATE OR REPLACE VIEW mgn.v_avance AS
SELECT
    lote,
    estado_revision,
    count(*)                                   AS poligonos,
    round((sum(ST_Area(geom)) / 10000.0)::numeric, 2) AS hectareas,
    max(fecha_edicion)                         AS ultima_edicion,
    string_agg(DISTINCT editado_por, ', ')     AS editoras
FROM mgn.deteccion_cambio
GROUP BY lote, estado_revision
ORDER BY lote, estado_revision;

GRANT SELECT ON mgn.v_avance TO edit_lote_a, edit_lote_b;


