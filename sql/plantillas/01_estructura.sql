COMMENT ON SCHEMA <<<ESQUEMA>>> IS
    '<<<DESCRIPCION_DEL_PROYECTO>>>';


-- =====================================================================================
--  BLOQUE 2 — Tabla principal
-- =====================================================================================
--  CAMBIA SEGÚN EL CASO: casi todo. Esta es la parte que más trabajo requiere.
--
--  TRES REGLAS QUE NO SE NEGOCIAN, independientemente del caso:
--
--   1. LLAVE PRIMARIA ENTERA ÚNICA.
--      QGIS necesita un entero para editar una capa PostGIS de forma confiable.
--      Si la capa de origen trae un identificador de texto, se conserva aparte
--      (columna id_origen) y NO se usa como llave primaria.
--      Se usa GENERATED BY DEFAULT, no ALWAYS, para que QGIS pueda insertar.
--
--   2. COLUMNA DE REPARTO, NOT NULL Y CON CHECK.
--      Es la columna sobre la que opera el control de acceso del archivo 03.
--      Un NULL ahí deja una fila sin dueña: nadie puede editarla.
--      El CHECK garantiza que solo existan los valores previstos.
--
--   3. GEOMETRÍA CON TIPO Y SRC EXPLÍCITOS.
--      geometry(MultiPolygon, 5367) y no geometry a secas. Declararlo obliga a que
--      todo lo que entre esté en el mismo sistema, que es lo que evita que los
--      cálculos de área den números absurdos.
--      Para capas de líneas usar MultiLineString; para puntos, Point.
-- =====================================================================================

CREATE TABLE <<<ESQUEMA>>>.<<<TABLA>>> (

    -- ---- Identificación (dejar tal cual) ----
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origen           text,

    -- ---- Columna de reparto ----
    -- CAMBIA SEGÚN EL CASO: el nombre de la columna y la lista de valores.
    -- El nombre debe describir cómo se repartieron el trabajo. Ejemplos reales:
    --    provincia  CHECK (provincia IN ('Limón','Guanacaste'))
    --    lote       CHECK (lote IN ('A','B'))
    --    canton     CHECK (canton IN ('Pérez Zeledón','Buenos Aires','Osa'))
    --    zona       CHECK (zona IN ('Norte','Centro','Sur'))
    -- La lista debe tener UN valor por cada persona que va a editar.
    <<<COLUMNA_REPARTO>>>  text  NOT NULL
        CHECK (<<<COLUMNA_REPARTO>>> IN (<<<'VALOR_1','VALOR_2','VALOR_3'>>>)),

    -- ---- Atributos propios de la capa ----
    -- CAMBIA SEGÚN EL CASO: enteramente. Acá van las columnas que ya tiene la capa
    -- de origen, con el tipo que corresponda. Guía rápida de tipos:
    --    texto, códigos, nombres ................ text
    --    números enteros, años, conteos ......... integer
    --    decimales, áreas, probabilidades ....... double precision
    --    fechas ................................. date
    --    fecha y hora ........................... timestamptz
    --    verdadero/falso ........................ boolean
    --
    -- NOMBRES PROHIBIDOS: hay palabras reservadas de SQL que no se pueden usar como
    -- nombre de columna sin complicaciones. Las más comunes en capas vectoriales:
    --    count, order, group, user, table, column, select, from, where, check,
    --    end, all, any, case, default, limit, offset, union, desc, asc
    -- Si la capa de origen trae una de esas, renombrarla acá (count -> conteo).
    --
    -- Reemplazar las tres líneas de ejemplo por las columnas reales:
    <<<ATRIBUTO_1>>>    text,
    <<<ATRIBUTO_2>>>    integer,
    <<<ATRIBUTO_3>>>    double precision,

    -- ---- Control de avance (dejar tal cual; ajustar los estados si hace falta) ----
    -- CAMBIA SEGÚN EL CASO: solo si el flujo de trabajo tiene otras etapas.
    estado_revision     text        NOT NULL DEFAULT 'pendiente'
                                    CHECK (estado_revision IN
                                        ('pendiente','en_proceso','revisado','validado','descartado')),
    observaciones       text,

    -- ---- Auditoría (dejar tal cual) ----
    -- Las llena sola el trigger del Bloque 4. No tocar.
    creado_por          text        NOT NULL DEFAULT current_user,
    fecha_creacion      timestamptz NOT NULL DEFAULT now(),
    editado_por         text        NOT NULL DEFAULT current_user,
    fecha_edicion       timestamptz NOT NULL DEFAULT now(),

    -- ---- Geometría ----
    -- CAMBIA SEGÚN EL CASO: el tipo y el código EPSG.
    -- En Costa Rica el oficial es CRTM05 = EPSG:5367.
    geom                geometry(<<<TIPO_GEOMETRIA>>>, <<<EPSG>>>) NOT NULL
);

COMMENT ON TABLE <<<ESQUEMA>>>.<<<TABLA>>> IS
    'Capa única de edición concurrente. Reparto por <<<COLUMNA_REPARTO>>>.';
COMMENT ON COLUMN <<<ESQUEMA>>>.<<<TABLA>>>.<<<COLUMNA_REPARTO>>> IS
    'Determina qué persona puede escribir la fila. No modificar sin coordinación.';


-- =====================================================================================
--  BLOQUE 3 — Índices
-- =====================================================================================
--  CAMBIA SEGÚN EL CASO: solo los nombres (prefijo) y la lista de columnas extra.
--  Los dos primeros son obligatorios en cualquier caso.
-- =====================================================================================

-- Índice espacial. OBLIGATORIO. Sin esto, navegar la capa en QGIS es lento.
CREATE INDEX idx_<<<PREFIJO>>>_geom
    ON <<<ESQUEMA>>>.<<<TABLA>>> USING GIST (geom);

-- Índice sobre la columna de reparto. OBLIGATORIO: lo usan el control de acceso
-- y el filtro que cada persona aplica en QGIS para ver solo su parte.
CREATE INDEX idx_<<<PREFIJO>>>_reparto
    ON <<<ESQUEMA>>>.<<<TABLA>>> (<<<COLUMNA_REPARTO>>>);

-- Índice sobre el estado. Recomendado: lo usa el panel de seguimiento.
CREATE INDEX idx_<<<PREFIJO>>>_estado
    ON <<<ESQUEMA>>>.<<<TABLA>>> (estado_revision);


-- =====================================================================================
--  BLOQUE 4 — Trigger de auditoría
-- =====================================================================================
--  NO CAMBIA SEGÚN EL CASO, salvo el nombre del esquema y de la tabla.
--
--  Registra automáticamente quién tocó cada registro y cuándo. No depende de que la
--  persona llene el campo. En INSERT fija creación y edición; en UPDATE preserva la
--  creación original e ignora cualquier intento de sobrescribirla desde el cliente.
--
--  Esto es lo que hace posible el seguimiento del archivo 04. Sin el trigger no hay
--  forma de saber quién editó qué.
-- =====================================================================================

CREATE OR REPLACE FUNCTION <<<ESQUEMA>>>.fn_sello_auditoria()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.creado_por     := current_user;
        NEW.fecha_creacion := now();
    ELSE
        NEW.creado_por     := OLD.creado_por;
        NEW.fecha_creacion := OLD.fecha_creacion;
    END IF;

    NEW.editado_por   := current_user;
    NEW.fecha_edicion := now();

    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sello_auditoria
    BEFORE INSERT OR UPDATE ON <<<ESQUEMA>>>.<<<TABLA>>>
    FOR EACH ROW EXECUTE FUNCTION <<<ESQUEMA>>>.fn_sello_auditoria();


