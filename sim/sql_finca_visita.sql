-- =====================================================================================
--  sim.finca_visita — capa de visita a escala (misma estructura que mgn.finca_visita,
--  sql/06). Un punto por UGM con ST_PointOnSurface. Sin RLS ni GRANT a roles de
--  edición: roles nuevos y RLS por provincia están fuera del alcance de S04.
--  Ejecutar: py sim/psql.py --evidencia 04_finca_visita.txt -f sim/sql_finca_visita.sql -- --echo-queries
-- =====================================================================================
\timing on

CREATE TABLE sim.finca_visita (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    finca_id            bigint NOT NULL
                        REFERENCES sim.ugm(id) ON DELETE CASCADE,
    lote                text    NOT NULL CHECK (lote IN ('1','2','3','4','5','6','7')),
    codigo_upm          text,
    estado_visita       text    NOT NULL DEFAULT 'pendiente'
                                CHECK (estado_visita IN
                                    ('pendiente','visitada','no_localizada',
                                     'rechazo','revisita')),
    encuestador         text,
    fecha_visita        timestamptz,
    observaciones       text,
    precision_gnss_m    double precision,
    posicion_registro   geometry(Point, 4326),
    creado_por          text        NOT NULL DEFAULT current_user,
    fecha_creacion      timestamptz NOT NULL DEFAULT now(),
    editado_por         text        NOT NULL DEFAULT current_user,
    fecha_edicion       timestamptz NOT NULL DEFAULT now(),
    geom                geometry(Point, 5367) NOT NULL,
    UNIQUE (finca_id)
);
COMMENT ON TABLE sim.finca_visita IS
    'Simulación S04: un punto de visita por UGM (D-18). codigo_upm = id_origen de la UGM.';

CREATE TRIGGER trg_sello_auditoria
    BEFORE INSERT OR UPDATE ON sim.finca_visita
    FOR EACH ROW EXECUTE FUNCTION sim.fn_sello_auditoria();

CREATE OR REPLACE FUNCTION sim.fn_fecha_visita_auto()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.estado_visita <> 'pendiente' AND NEW.fecha_visita IS NULL THEN
        NEW.fecha_visita := now();
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_fecha_visita_auto
    BEFORE INSERT OR UPDATE ON sim.finca_visita
    FOR EACH ROW EXECUTE FUNCTION sim.fn_fecha_visita_auto();

-- Un punto por polígono (medido con \timing)
INSERT INTO sim.finca_visita (finca_id, lote, codigo_upm, geom)
SELECT id, lote, id_origen, ST_PointOnSurface(geom)
FROM sim.ugm;

CREATE INDEX idx_sfv_geom   ON sim.finca_visita USING GIST (geom);
CREATE INDEX idx_sfv_lote   ON sim.finca_visita (lote);
CREATE INDEX idx_sfv_estado ON sim.finca_visita (estado_visita);
CREATE INDEX idx_sfv_finca  ON sim.finca_visita (finca_id);
ANALYZE sim.finca_visita;

\timing off
-- Verificación: puntos = polígonos = dentro
SELECT (SELECT count(*) FROM sim.ugm) AS poligonos,
       count(*) AS puntos,
       count(*) FILTER (WHERE ST_Within(v.geom, u.geom)) AS dentro
FROM sim.finca_visita v
JOIN sim.ugm u ON u.id = v.finca_id;

SELECT lote, count(*) AS puntos,
       count(*) FILTER (WHERE estado_visita = 'pendiente') AS pendientes
FROM sim.finca_visita GROUP BY lote ORDER BY lote;
