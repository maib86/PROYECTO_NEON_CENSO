-- =====================================================================================
--  Columna de reparto `lote` = código de provincia (primer dígito de cod_uged).
--  Ejecutar: py sim/cargar_ugm.py ugm   (como neondb_owner)
-- =====================================================================================
\timing on

CREATE TABLE sim.ugm (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_origen           text,
    lote                text NOT NULL
                        CHECK (lote IN ('1','2','3','4','5','6','7')),
    provincia           text,
    canton              text,
    distrito            text,
    cod_distrito        text,
    id_mgn              bigint,
    area_m2             double precision,
    fecha_act           text,
    estado_revision     text        NOT NULL DEFAULT 'pendiente'
                                    CHECK (estado_revision IN
                                        ('pendiente','en_proceso','revisado','validado','descartado')),
    observaciones       text,
    creado_por          text        NOT NULL DEFAULT current_user,
    fecha_creacion      timestamptz NOT NULL DEFAULT now(),
    editado_por         text        NOT NULL DEFAULT current_user,
    fecha_edicion       timestamptz NOT NULL DEFAULT now(),
    geom                geometry(MultiPolygon, 5367) NOT NULL
);
COMMENT ON TABLE sim.ugm IS
    'Simulación S04: UGM del SNIT como proxy de fincas (D-18). Reparto por lote = provincia.';

CREATE OR REPLACE FUNCTION sim.fn_sello_auditoria()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        NEW.creado_por     := current_user;
        NEW.fecha_creacion := now();
    ELSE
        NEW.creado_por     := OLD.creado_por;
        NEW.fecha_creacion := OLD.fecha_creacion;
    END IF;
    NEW.editado_por   := current_user;
    NEW.fecha_edicion := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_sello_auditoria
    BEFORE INSERT OR UPDATE ON sim.ugm
    FOR EACH ROW EXECUTE FUNCTION sim.fn_sello_auditoria();

-- Carga (medida con \timing)
INSERT INTO sim.ugm (id_origen, lote, provincia, canton, distrito, cod_distrito,
                     id_mgn, area_m2, fecha_act, geom)
SELECT id::bigint::text,
       substr(cod_uged, 1, 1),
       nomb_ugep, nomb_ugec, nomb_uged, cod_uged,
       id_mgn::bigint, area_m2, fecha_act,
       ST_Multi(ST_MakeValid(geom))
FROM sim.carga_temporal;

-- Índices después de cargar (más rápido que mantenerlos fila a fila)
CREATE INDEX idx_sugm_geom    ON sim.ugm USING GIST (geom);
CREATE INDEX idx_sugm_reparto ON sim.ugm (lote);
CREATE INDEX idx_sugm_estado  ON sim.ugm (estado_revision);

ALTER TABLE sim.ugm ADD CONSTRAINT chk_geom_valida CHECK (ST_IsValid(geom)) NOT VALID;
ALTER TABLE sim.ugm VALIDATE CONSTRAINT chk_geom_valida;
ANALYZE sim.ugm;

\timing off
-- Verificaciones (plantilla 02)
SELECT count(*) AS total, count(DISTINCT id_origen) AS id_origen_distintos FROM sim.ugm;
SELECT lote, provincia, count(*) FROM sim.ugm GROUP BY 1, 2 ORDER BY 1;
SELECT count(*) AS invalidas FROM sim.ugm WHERE NOT ST_IsValid(geom);
SELECT DISTINCT ST_SRID(geom) AS srid, GeometryType(geom) AS tipo FROM sim.ugm;
SELECT round((sum(ST_Area(geom)) / 10000.0)::numeric, 2) AS hectareas_calculadas,
       round((sum(area_m2) / 10000.0)::numeric, 2)       AS hectareas_origen
FROM sim.ugm;

